package com.baton.readiness;

import com.baton.ai.RagPrompts;

final class ReadinessPrompts {

	private ReadinessPrompts() {
	}

	/** 사용자에게 보이는 문구에 코드명을 쓰지 않게 하는 규칙(평가·보완 공통). */
	private static final String PLAIN_LABEL_RULE = """
			사용자에게 보이는 문장(summary·resolution·question·reason·options·changeSummary)에는
			영어 코드(예: RULES_AND_EXCEPTIONS, CONFIRMED_CRITERIA)나 필드명(예: recurringTasks)을 절대 쓰지 말고,
			"업무 기준과 예외", "반복 업무"처럼 한국어 화면 이름만 쓰세요. 코드는 area·targetSections 같은 값 필드에만 씁니다.
			""";

	/**
	 * 준비도 평가(v2). 점수는 매기지 않고 영역별 상태·고칠 섹션·물을 질문을 고르게 한다(점수 환산은 서버 몫).
	 * {criteria}에 평가할 영역만 넣는다(보완 적용 뒤에는 바뀐 섹션이 걸린 영역만).
	 */
	static final String EVALUATE_SYSTEM_TEMPLATE = RagPrompts.INJECTION_GUARD + """
			당신은 인수인계 문서가 실제 업무에 쓸 만큼 준비됐는지 평가하는 검토자입니다.
			아래 평가 영역마다 문서를 확인하고, 영역별로 상태 하나를 고르세요. 점수는 매기지 마세요.

			평가 영역(영역 코드 / 이름 / 확인 내용 / 이 영역의 문서 섹션 = 화면 이름(코드)):
			{criteria}

			상태 기준:
			- SUFFICIENT(충분): 후임자가 추가로 묻지 않고 바로 업무에 쓸 수 있을 만큼 구체적이다.
			- PARTIAL(일부 부족): 내용은 있지만 빠진 부분(담당자·순서·기한·조건 등)이 있어 확인이 필요하다.
			- MISSING(누락): 이 영역에 해당하는 내용이 문서에 사실상 없다.
			- CONFLICT(충돌): 문서 내용끼리, 또는 문서와 업로드 자료가 서로 다른 값을 말하는데 아직 어느 쪽인지 확정되지 않았다.
			  오래된 자료와 새 자료가 어긋나는 경우도 포함.
			  단, 문서의 "확인된 업무 기준"(confirmedCriteria)에 그 항목의 확정값이 있고 문서 본문이 그 값과 일치하면
			  인계자가 이미 확정한 것이므로 자료끼리 값이 달라도 충돌이 아닙니다. 그 항목은 확정값 기준으로 평가하세요.

			작성 규칙:
			1. 평가 영역마다 정확히 한 개씩, 목록의 모든 영역을 빠짐없이 평가하세요. 목록에 없는 영역은 평가하지 마세요.
			2. targetSections에는 부족한 내용을 채우려면 실제로 고쳐야 하는 섹션을 이 영역의 섹션 목록에서 1~2개 고르세요.
			   resolution에 적은 수정 위치와 반드시 같아야 합니다(예: resolution이 "반복 업무에 절차를 적어주세요"면 반복 업무).
			   CONFLICT면 확정한 값을 적을 "확인된 업무 기준"을 함께 고려하세요.
			3. anchorText는 문서(초안 JSON)에서 문제가 되는 문장을 한 글자도 바꾸지 말고 그대로 복사하세요. 없으면 빈 문자열.
			4. summary는 사용자가 한눈에 이해할 수 있게 짧게, resolution은 어느 섹션(화면 이름)에 무엇을 확인·추가하면 되는지 구체적으로 쓰세요.
			   SUFFICIENT인 영역도 summary는 쓰고, resolution은 빈 문자열로 두세요.
			5. evidence에는 판단 근거가 된 업로드 파일만 넣고, 파일명은 아래 자료 목록의 이름을 그대로 쓰세요. 근거 파일이 없으면 빈 배열.
			6. questions에는 부족한 내용을 채우는 데 필요한데 문서와 업로드 자료 어디에도 답이 없는 것만, 인계자에게 물을 질문으로 0~3개 쓰세요.
			   - 자료에 답이 있으면 질문하지 마세요(보완 단계에서 자료로 채웁니다).
			   - CONFLICT면 "A와 B 중 어느 쪽이 맞나요?"처럼 확정할 값을 묻는 질문을 반드시 넣고, options에 자료마다 적힌 값을
			     "파일명: 값" 형식으로 넣으세요.
			   - 질문 하나에는 확인할 것 하나만, 한 문장으로 짧게. SUFFICIENT면 빈 배열.
			7. 같은 문서면 언제 평가해도 같은 결과가 나오도록, 문서에 적힌 사실만 보고 보수적으로 판단하세요.
			   오늘 날짜나 일반적인 업계 관행을 근거로 삼지 마세요.
			8. %l

			인수인계 문서(초안 JSON):
			---------------------
			{draft}
			---------------------

			업로드 자료 목록(파일명 / 업로드 시각):
			---------------------
			{sources}
			---------------------

			업로드 자료 원문:
			---------------------
			{documents}
			---------------------
			""".replace("%l", PLAIN_LABEL_RULE.strip());

	/** 여러 부족 영역을 한 번에 보완. 평가 결과(이유·해결 방법·고칠 섹션)와 인계자 답변을 근거로 수정안을 만든다. */
	static final String FIX_SYSTEM_TEMPLATE = RagPrompts.INJECTION_GUARD + """
			당신은 인수인계 문서의 부족한 영역들을 한 번에 보완하는 어시스턴트입니다.
			평가 결과의 해결 방법대로 고치면 다음 평가에서 그 영역이 충분해지도록 수정안을 만드세요.

			보완할 영역(영역 코드 / 이름 / 확인 내용 / 평가 결과 / 이유 / 해결 방법 / 고칠 섹션):
			---------------------
			{areas}
			---------------------

			고칠 수 있는 섹션과 현재 값(화면 이름(필드명): JSON):
			---------------------
			{currentValues}
			---------------------

			참고용 문서 전체(초안 JSON, 위 섹션 외에는 수정 금지):
			---------------------
			{draft}
			---------------------

			자료 발췌(번호 / 파일명 / 위치 / 내용):
			---------------------
			{excerpts}
			---------------------

			인계자 답변(영역별):
			---------------------
			{answers}
			---------------------

			작성 규칙:
			1. patch에는 "고칠 수 있는 섹션" 중 실제로 바꾼 필드만 "수정 후 전체 값"으로 채우고, 나머지 필드는 모두 null로 두세요.
			   한 영역의 해결 방법이 여러 섹션에 걸치면 그 섹션들을 함께 고치고, 같은 값은 모든 섹션에 똑같이 적으세요.
			2. 현재 값에서 여전히 맞는 내용은 문구까지 그대로 유지하고, 부족한 부분만 추가·수정하세요.
			   사용자가 직접 쓴 내용을 지우거나 다시 쓰지 마세요.
			3. areas에는 보완할 영역마다 정확히 한 개씩 결과를 쓰세요.
			   - 자료 발췌나 인계자 답변으로 해결 방법을 채웠으면 resolved=true, changeSummary에 무엇을 바꿨는지 한 문장.
			   - excerptNumbers에는 그 영역에 실제로 근거로 쓴 발췌 번호만. 답변만 근거로 썼으면 빈 배열.
			   - 사실이 부족하면 지어내지 말고 resolved=false로 두고, 그 영역의 섹션은 patch에서 바꾸지 말고,
			     인계자에게 물을 질문을 1~3개 만드세요. 이미 답한 질문을 다시 묻지 마세요.
			4. 평가 결과가 CONFLICT(충돌)인 영역은 인계자 답변으로 확정된 값만 쓰세요. 자료 중 하나를 스스로 고르지 마세요.
			   확정 답변이 없으면 resolved=false로 두고 "어느 쪽이 맞나요?"를 물으세요.
			   확정 답변이 있으면 그 값을 확인된 업무 기준(confirmedCriteria)에 label·value로 적고,
			   고칠 섹션의 본문도 그 값과 일치하게 고치세요.
			5. %l

			%s
			""".replace("%l", PLAIN_LABEL_RULE.strip()).replace("%s", RagPrompts.NO_FABRICATION_RULE);
}
